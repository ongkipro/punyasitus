export const GenericExtensionPayloadSchema = z
  .record(z.string(), z.unknown())
  .meta({ description: "Structured JSON request payload validated by the owning endpoint handler." });

export const GenericExtensionResponseSchema = z
  .object({
    success: z.boolean().optional(),
    data: z.unknown().optional(),
  })
  .catchall(z.unknown())
  .meta({ description: "Structured JSON response payload returned by the endpoint." });

const PathSegmentSchema = z.string().min(1).max(200);

function makePathParam(name: string): RouteParameterContract {
  if (name === "tenantId") return TENANT_HANDLE_PATH_PARAM;
  return {
    name,
    in: "path",
    required: true,
    description: `Path parameter "${name}"`,
    schema: PathSegmentSchema,
  };
}

