function startCompiledAssetServer(outDir) {
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      const reqUrl = new URL(req.url || "/", "http://127.0.0.1");
      const p = reqUrl.pathname;

      if (p === "/media/alpha-hero.svg" || p === "/media/beta-hero.svg") {
        const bg = p.includes("alpha") ? "#176b51" : "#1f4f82";
        const label = p.includes("alpha") ? "PT Alpha Arsitektur Mandiri" : "Beta Klinik Trial";
        res.writeHead(200, { "Content-Type": "image/svg+xml; charset=utf-8" });
        res.end(
          `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630"><rect width="1200" height="630" fill="${bg}"/><text x="80" y="320" fill="#ffffff" font-size="48" font-family="system-ui, sans-serif">${label}</text></svg>`,
        );
        return;
      }

      const candidates = [
        path.join(outDir, p === "/" ? "index.html" : p),
        path.join(outDir, p, "index.html"),
        path.join(outDir, `${p}.html`),
      ];
      let filePath = null;
      for (const c of candidates) {
        if (fs.existsSync(c) && fs.statSync(c).isFile()) {
          filePath = c;
          break;
        }
      }
      if (!filePath) {
        res.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
        res.end("Not found");
        return;
      }

      const ext = path.extname(filePath).toLowerCase();
      const mime =
        ext === ".html"
          ? "text/html; charset=utf-8"
          : ext === ".xml"
            ? "application/xml; charset=utf-8"
            : ext === ".txt"
              ? "text/plain; charset=utf-8"
              : ext === ".css"
                ? "text/css; charset=utf-8"
                : ext === ".js"
                  ? "application/javascript; charset=utf-8"
                  : "application/octet-stream";
      res.writeHead(200, { "Content-Type": mime });
      fs.createReadStream(filePath).pipe(res);
    });

    server.listen(0, "127.0.0.1", () => {
      const addr = server.address();
      resolve({ server, baseUrl: `http://127.0.0.1:${addr.port}` });
    });
  });
}

async function inspectRenderedCrawlPage(page) {
  return page.evaluate(() => {
    const titles = document.querySelectorAll("head title");
    const descriptions = document.querySelectorAll('head meta[name="description"]');
    const robots = Array.from(document.querySelectorAll('head meta[name="robots"]')).map(
      (el) => el.getAttribute("content") || "",
    );
    const canonicals = Array.from(document.querySelectorAll('head link[rel="canonical"]')).map(
      (el) => el.getAttribute("href") || "",
    );
    const jsonLds = Array.from(document.querySelectorAll('script[type="application/ld+json"]')).map(
      (el) => el.textContent || "",
    );
    const nonJsonLdScripts = Array.from(document.querySelectorAll("script")).filter(
      (s) => (s.getAttribute("type") || "").toLowerCase() !== "application/ld+json",
    );
    const externalScriptCount = nonJsonLdScripts.filter((s) => s.hasAttribute("src")).length;
    const hasInjectedScriptPayload = nonJsonLdScripts.some((s) =>
      /alert\s*\(|xss/i.test(s.textContent || ""),
    );
    const inlineEventAttrs = Array.from(document.querySelectorAll("*")).filter((el) =>
      Array.from(el.attributes).some((attr) => /^on[a-z]+$/i.test(attr.name)),
    );
    const mapIframes = document.querySelectorAll(
      'iframe[src*="maps"], iframe[src*="openstreetmap"]',
    ).length;
    const gsc =
      document.querySelector('head meta[name="google-site-verification"]')?.getAttribute("content") ||
      null;
    const bing =
      document.querySelector('head meta[name="msvalidate.01"]')?.getAttribute("content") || null;
    const hrefs = Array.from(document.querySelectorAll("a[href]"))
      .map((a) => a.getAttribute("href") || "")
      .filter((h) => h.startsWith("/"));
    const heroImg = document.querySelector(".ps-hero-media img");
    const h1Count = document.querySelectorAll("h1").length;
    const overflow = document.documentElement.scrollWidth - window.innerWidth;

    return {
      titleCount: titles.length,
      titleText: titles[0]?.textContent || "",
      descriptionCount: descriptions.length,
      robotsCount: robots.length,
      robots: robots[0] || "",
      canonicalCount: canonicals.length,
      canonical: canonicals[0] || "",
      jsonLdCount: jsonLds.length,
      jsonLdRaw: jsonLds[0] || "",
      nonJsonLdScriptCount: nonJsonLdScripts.length,
      externalScriptCount,
      hasInjectedScriptPayload,
      inlineEventAttrCount: inlineEventAttrs.length,
      mapIframes,
      gsc,
      bing,
      hrefs,
      heroLoading: heroImg?.getAttribute("loading") || null,
      heroWidth: heroImg?.getAttribute("width") || null,
      heroHeight: heroImg?.getAttribute("height") || null,
      h1Count,
      overflow,
      html: document.documentElement.outerHTML,
    };
  });
}

